open Claudius

let of_backend_keycode (keycode : int) : Key.t =
  match keycode with
  (* Arrow Keys *)
  | 39 -> Key.Right
  | 37 -> Key.Left
  | 40 -> Key.Down
  | 38 -> Key.Up
  (* Modifier Keys *)
  | 16 -> Key.Shift_L
  (* | 16 -> Key.Shift_R *)
  | 17 -> Key.Control_L
  (* | 17 -> Key.Control_R *)
  | 18 -> Key.Alt_L
  (* | 18 -> Key.Alt_R *)
  | 20 -> Key.CapsLock
  (* Function Keys *)
  | 112 -> Key.F1
  | 113 -> Key.F2
  | 114 -> Key.F3
  | 115 -> Key.F4
  | 116 -> Key.F5
  | 117 -> Key.F6
  | 118 -> Key.F7
  | 119 -> Key.F8
  | 120 -> Key.F9
  | 121 -> Key.F10
  | 122 -> Key.F11
  | 123 -> Key.F12
  (* Navigation Keys *)
  | 0x40000049 -> Key.Insert
  | 0x4000007F -> Key.Delete
  | 0x4000004A -> Key.Home
  | 0x4000004D -> Key.End
  | 0x4000004B -> Key.PageUp
  | 0x4000004E -> Key.PageDown
  (* Common Control Keys *)
  | 32 -> Key.Space
  | 27 -> Key.Escape
  | 13 -> Key.Enter
  | 8 -> Key.Backspace
  | 9 -> Key.Tab
  (* Alphabet Keys (Lowercase) *)
  | 65 -> Key.A
  | 66 -> Key.B
  | 67 -> Key.C
  | 68 -> Key.D
  | 69 -> Key.E
  | 70 -> Key.F
  | 71 -> Key.G
  | 72 -> Key.H
  | 73 -> Key.I
  | 74 -> Key.J
  | 75 -> Key.K
  | 76 -> Key.L
  | 77 -> Key.M
  | 78 -> Key.N
  | 79 -> Key.O
  | 80 -> Key.P
  | 81 -> Key.Q
  | 82 -> Key.R
  | 83 -> Key.S
  | 84 -> Key.T
  | 85 -> Key.U
  | 86 -> Key.V
  | 87 -> Key.W
  | 88 -> Key.X
  | 89 -> Key.Y
  | 90 -> Key.Z
  (* Number Keys *)
  | 48 -> Key.Num0
  | 49 -> Key.Num1
  | 50 -> Key.Num2
  | 51 -> Key.Num3
  | 52 -> Key.Num4
  | 53 -> Key.Num5
  | 54 -> Key.Num6
  | 55 -> Key.Num7
  | 56 -> Key.Num8
  | 57 -> Key.Num9
  (* Unknown Key *)
  | _ -> Key.Unknown

let to_backend_keycode (key : Key.t) : int =
  match key with
  (* Arrow Keys *)
  | Key.Right -> 39
  | Key.Left -> 37
  | Key.Down -> 40
  | Key.Up -> 38
  (* Modifier Keys *)
  | Key.Shift_L -> 16
  | Key.Shift_R -> 16
  | Key.Control_L -> 17
  | Key.Control_R -> 17
  | Key.Alt_L -> 18
  | Key.Alt_R -> 18
  | Key.CapsLock -> 20
  | Key.NumLock -> 0x40000053
  | Key.ScrollLock -> 0x40000047
  (* Function Keys *)
  | Key.F1 -> 112
  | Key.F2 -> 113
  | Key.F3 -> 114
  | Key.F4 -> 115
  | Key.F5 -> 116
  | Key.F6 -> 117
  | Key.F7 -> 118
  | Key.F8 -> 119
  | Key.F9 -> 120
  | Key.F10 -> 121
  | Key.F11 -> 122
  | Key.F12 -> 123
  (* Navigation Keys *)
