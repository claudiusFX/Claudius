  | Key.Delete -> 0x4000007F
  | Key.Home -> 0x4000004A
  | Key.End -> 0x4000004D
  | Key.PageUp -> 0x4000004B
  | Key.PageDown -> 0x4000004E
  (* Common Control Keys *)
  | Key.Space -> 32
  | Key.Escape -> 27
  | Key.Enter -> 13
  | Key.Backspace -> 8
  | Key.Tab -> 9
  | Key.PrintScreen -> 0x40000046
  | Key.Pause -> 0x40000048
  (* Alphabet Keys (Lowercase) *)
  | Key.A -> 65
  | Key.B -> 66
  | Key.C -> 67
  | Key.D -> 68
  | Key.E -> 69
  | Key.F -> 70
  | Key.G -> 71
  | Key.H -> 72
  | Key.I -> 73
  | Key.J -> 74
  | Key.K -> 75
  | Key.L -> 76
  | Key.M -> 77
  | Key.N -> 78
  | Key.O -> 79
  | Key.P -> 80
  | Key.Q -> 81
  | Key.R -> 82
  | Key.S -> 83
  | Key.T -> 84
  | Key.U -> 85
  | Key.V -> 86
  | Key.W -> 87
  | Key.X -> 88
  | Key.Y -> 89
  | Key.Z -> 90
  (* Number Keys *)
  | Key.Num0 -> 48
  | Key.Num1 -> 49
  | Key.Num2 -> 50
  | Key.Num3 -> 51
  | Key.Num4 -> 52
  | Key.Num5 -> 53
  | Key.Num6 -> 54
  | Key.Num7 -> 55
  | Key.Num8 -> 56
  | Key.Num9 -> 57
  (* Unknown Key *)
  | Key.Unknown -> -1
